// Command genwrappers generates the root package's operation methods and type
// aliases from the oapi-codegen output in api/api.gen.go.
//
// Usage (from the repository root):
//
//	go run ./internal/cmd/genwrappers
package main

import (
	"bytes"
	"fmt"
	"go/ast"
	"go/format"
	"go/parser"
	"go/printer"
	"go/token"
	"log"
	"os"
	"sort"
	"strings"
)

const (
	input       = "api/api.gen.go"
	opsOutput   = "operations.gen.go"
	typesOutput = "types.gen.go"
	header      = "// Code generated by internal/cmd/genwrappers. DO NOT EDIT.\n\npackage rask\n\n"
)

// Generated identifiers that belong to the low-level client and must not be
// re-exported from the root package.
var skipTypes = map[string]bool{
	"Client":                       true,
	"ClientInterface":              true,
	"ClientOption":                 true,
	"ClientWithResponses":          true,
	"ClientWithResponsesInterface": true,
	"HttpRequestDoer":              true,
	"RequestEditorFn":              true, // declared in client.go
}

// Set by main: names re-exported by types.gen.go, and request-body aliases
// (XJSONRequestBody = Y) resolved to their target type.
var (
	reexported  = map[string]bool{}
	bodyAliases = map[string]string{}
)

// Operations wrapped by hand because their request body is multipart.
var handWritten = map[string]bool{
	"CreateMediaFile":        true,
	"CreateTranscriptionSrt": true,
}

type operation struct {
	name    string
	doc     []string
	params  []*ast.Field
	result  ast.Expr // type of JSON200, nil when the operation has no JSON body
	sliceOf bool     // result is *[]T and is returned as []T
}

func main() {
	fset := token.NewFileSet()
	file, err := parser.ParseFile(fset, input, nil, parser.ParseComments)
	if err != nil {
		log.Fatal(err)
	}

	responses := map[string]*ast.StructType{}
	var candidates, typeNames, constNames []string
	var ops []operation

	for _, decl := range file.Decls {
		switch d := decl.(type) {
		case *ast.GenDecl:
			for _, spec := range d.Specs {
				switch s := spec.(type) {
				case *ast.TypeSpec:
					name := s.Name.Name
					if st, ok := s.Type.(*ast.StructType); ok && hasField(st, "HTTPResponse") {
						// <Op>Response wrapper, replaced by the typed methods.
						responses[name] = st
						continue
					}
					if target, ok := s.Type.(*ast.Ident); ok && s.Assign.IsValid() && strings.HasSuffix(name, "RequestBody") {
						bodyAliases[name] = target.Name
						continue
					}
					if ast.IsExported(name) && !skipTypes[name] {
						candidates = append(candidates, name)
					}
				case *ast.ValueSpec:
					if d.Tok != token.CONST {
						continue
					}
					for _, n := range s.Names {
						if n.IsExported() {
							constNames = append(constNames, n.Name)
						}
					}
				}
			}
		case *ast.FuncDecl:
			if op, ok := parseOperation(d); ok {
				ops = append(ops, op)
			}
		}
	}

	for _, name := range candidates {
		if responses[name] == nil {
			typeNames = append(typeNames, name)
			reexported[name] = true
		}
	}

	for i := range ops {
		st := responses[ops[i].name+"Response"]
		if st == nil {
			log.Fatalf("no response type for %s", ops[i].name)
		}
		for _, f := range st.Fields.List {
			if len(f.Names) == 1 && f.Names[0].Name == "JSON200" {
				star := f.Type.(*ast.StarExpr)
				if arr, ok := star.X.(*ast.ArrayType); ok {
					ops[i].result, ops[i].sliceOf = arr, true
				} else {
					ops[i].result = star
				}
			}
		}
	}
	sort.Slice(ops, func(i, j int) bool { return ops[i].name < ops[j].name })
	sort.Strings(typeNames)
	sort.Strings(constNames)

	write(opsOutput, renderOperations(fset, ops))
	write(typesOutput, renderTypes(typeNames, constNames))
}

func hasField(st *ast.StructType, name string) bool {
	for _, f := range st.Fields.List {
		for _, n := range f.Names {
			if n.Name == name {
				return true
			}
		}
	}
	return false
}

func parseOperation(fn *ast.FuncDecl) (operation, bool) {
	if fn.Recv == nil || len(fn.Recv.List) != 1 {
		return operation{}, false
	}
	recv, ok := fn.Recv.List[0].Type.(*ast.StarExpr)
	if !ok || recv.X.(*ast.Ident).Name != "ClientWithResponses" {
		return operation{}, false
	}
	name, ok := strings.CutSuffix(fn.Name.Name, "WithResponse")
	if !ok || strings.HasSuffix(name, "WithBody") || handWritten[name] {
		return operation{}, false
	}
	params := fn.Type.Params.List
	// Drop ctx and the trailing reqEditors; they are added back explicitly.
	return operation{name: name, doc: docLines(fn), params: params[1 : len(params)-1]}, true
}

// docLines turns the generated method comment into the wrapper's comment:
// "<Op>WithResponse <summary>" becomes "<Op> <summary>", and the sentences
// about the low-level response wrapper are dropped.
func docLines(fn *ast.FuncDecl) []string {
	if fn.Doc == nil {
		return nil
	}
	var out []string
	for _, line := range strings.Split(fn.Doc.Text(), "\n") {
		if strings.HasPrefix(line, "Returns a wrapper object") || strings.HasPrefix(line, "Takes a") {
			continue
		}
		line = strings.Replace(line, "WithResponse ", " ", 1)
		out = append(out, line)
	}
	// Collapse blank lines left behind by the dropped sentences.
	var clean []string
	for i, l := range out {
		if l == "" && (i == 0 || out[i-1] == "" || i == len(out)-1) {
			continue
		}
		clean = append(clean, l)
	}
	return clean
}

func renderOperations(fset *token.FileSet, ops []operation) []byte {
	var b bytes.Buffer
	b.WriteString(header)
	b.WriteString("import \"context\"\n\n")

	for _, op := range ops {
		for _, l := range op.doc {
			if l == "" {
				b.WriteString("//\n")
			} else {
				fmt.Fprintf(&b, "// %s\n", l)
			}
		}
		var sig, args []string
		for _, p := range op.params {
			typ := qualify(expr(fset, p.Type))
			for _, n := range p.Names {
				sig = append(sig, n.Name+" "+typ)
				args = append(args, n.Name)
			}
		}
		sig = append(sig, "reqEditors ...RequestEditorFn")
		args = append(args, "reqEditors...")
		call := fmt.Sprintf("c.api.%sWithResponse(ctx, %s)", op.name, strings.Join(args, ", "))

		switch {
		case op.result == nil:
			fmt.Fprintf(&b, "func (c *Client) %s(ctx context.Context, %s) error {\n", op.name, strings.Join(sig, ", "))
			fmt.Fprintf(&b, "\tresp, err := %s\n\treturn checkStatus(resp, err)\n}\n\n", call)
		case op.sliceOf:
			typ := qualify(expr(fset, op.result))
			fmt.Fprintf(&b, "func (c *Client) %s(ctx context.Context, %s) (%s, error) {\n", op.name, strings.Join(sig, ", "), typ)
			fmt.Fprintf(&b, "\tresult, err := unwrap(%s)\n\tif err != nil {\n\t\treturn nil, err\n\t}\n\treturn *result, nil\n}\n\n", call)
		default:
			typ := qualify(expr(fset, op.result))
			fmt.Fprintf(&b, "func (c *Client) %s(ctx context.Context, %s) (%s, error) {\n", op.name, strings.Join(sig, ", "), typ)
			fmt.Fprintf(&b, "\treturn unwrap(%s)\n}\n\n", call)
		}
	}
	return b.Bytes()
}

func renderTypes(types, consts []string) []byte {
	var b bytes.Buffer
	b.WriteString(header)
	b.WriteString("import \"github.com/braskai/rask-sdk-go/api\"\n\n")
	b.WriteString("// Types re-exported from the generated api package.\ntype (\n")
	for _, t := range types {
		fmt.Fprintf(&b, "\t%s = api.%s\n", t, t)
	}
	b.WriteString(")\n\n// Enum values re-exported from the generated api package.\nconst (\n")
	for _, c := range consts {
		fmt.Fprintf(&b, "\t%s = api.%s\n", c, c)
	}
	b.WriteString(")\n")
	return b.Bytes()
}

func expr(fset *token.FileSet, e ast.Expr) string {
	var b bytes.Buffer
	if err := printer.Fprint(&b, fset, e); err != nil {
		log.Fatal(err)
	}
	return b.String()
}

// qualify prefixes the api package's exported identifiers and maps the
// runtime UUID type to the root package's UUID alias.
func qualify(typ string) string {
	prefix := ""
	for strings.HasPrefix(typ, "*") || strings.HasPrefix(typ, "[]") {
		if strings.HasPrefix(typ, "*") {
			prefix, typ = prefix+"*", typ[1:]
		} else {
			prefix, typ = prefix+"[]", typ[2:]
		}
	}
	if target, ok := bodyAliases[typ]; ok {
		typ = target
	}
	switch {
	case typ == "openapi_types.UUID":
		typ = "UUID"
	case reexported[typ]:
	case ast.IsExported(typ) && !strings.Contains(typ, "."):
		typ = "api." + typ
	}
	return prefix + typ
}

func write(path string, src []byte) {
	formatted, err := format.Source(src)
	if err != nil {
		log.Fatalf("format %s: %v\n%s", path, err, src)
	}
	if err := os.WriteFile(path, formatted, 0o644); err != nil {
		log.Fatal(err)
	}
}
